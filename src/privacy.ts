/**
 * 개인정보 보호 유틸리티.
 * 교사 입력에서 연락처·식별 번호·학생 식별 패턴을 감지합니다.
 * 이 필터는 보조 장치이며 완전한 익명화를 보장하지 않습니다.
 */

/** 개인정보 감지 패턴 목록. 순서대로 검사합니다. */
const patterns: RegExp[] = [
  // 전화번호 (010-1234-5678, 02-123-4567 등)
  /\b\d{2,3}[- ]?\d{3,4}[- ]?\d{4}\b/,
  // 이메일
  /[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}/,
  // 주민등록번호 (6자리-7자리)
  /\b\d{6}[- ]?\d{7}\b/,
  // 출석 번호 패턴 ("3번", "12번 학생") — \b는 한글 앞에서 작동하지 않으므로 대안 사용
  /(?:^|[^가-힣\d])\d{1,2}번(?:\s|$|[가-힣])/,
  // "OO 학생", "OO이가", "OO이는" 패턴 (한글 이름 + 호칭)
  /[가-힣]{2,4}\s*(?:학생|이가|이는|이의|에게|한테)/,
  // 학교 이름 패턴 ("OO초등학교", "OO초")
  /[가-힣]{2,10}(?:초등학교|초등|중학교|고등학교)/,
  // 학년-반 패턴 ("3학년 2반")
  /\d\s*학년\s*\d\s*반/,
];

/** 전화번호, 이메일, 주민등록번호, 출석번호, 학생 이름 패턴 감지. */
export function sensitive(text: string): boolean {
  return patterns.some(pattern => pattern.test(text));
}

/** 감지된 패턴의 종류를 반환합니다. 감지되지 않으면 null. */
export function detectSensitiveType(text: string): string | null {
  const labels = ['전화번호', '이메일', '주민등록번호', '출석번호', '학생 이름', '학교 이름', '학년·반'];
  for (let i = 0; i < patterns.length; i++) {
    if (patterns[i].test(text)) return labels[i];
  }
  return null;
}
